    public static string DisplayName(string name)
    {
        string translated;
        return PTVLang.Thai && name != null && ThaiNames.TryGetValue(name, out translated) ? translated : ListedName(name);
    }

    static string Token(string v) => new string((v ?? "").Where(char.IsLetterOrDigit).Select(char.ToLowerInvariant).ToArray());
    public static string MatchKey(string value)
    {
        if (aliases == null)
        {
            aliases = new Dictionary<string, string>();
            foreach (var n in Names) { aliases[Token(n)] = Token(n); aliases[Token(ListedName(n))] = Token(n); }
            aliases["donut"] = "doughnut";
            aliases["handheart"] = "handhearts";
            aliases["friendship"] = "friendshipnecklace";
        }
        var key = Token(value);
        return aliases.TryGetValue(key, out var canonical) ? canonical : key;
    }
    public static int Price(string name) { var _ = Names; return name != null && entries.TryGetValue(name, out var e) ? e.price : 0; }
    public static string PriceLabel(string name)
    {
        int amount = Price(name);
        return amount.ToString("N0") + (PTVLang.Thai ? " เหรียญ" : amount == 1 ? " coin" : " coins");
    }
    public static Sprite Icon(string name)
    {
        if (string.IsNullOrEmpty(name)) return null;
        if (!sprites.TryGetValue(name, out var s))
        {
            s = Resources.Load<Sprite>("PaintGifts/" + name);
            if (!s) foreach (var n in Names) if (MatchKey(n) == MatchKey(name)) { s = Resources.Load<Sprite>("PaintGifts/" + n); break; }
            sprites[name] = s;
        }
        return s;
    }
